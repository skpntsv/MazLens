package app.mazlens.core.protocol

/** Recorder refusals are distinct from transport failures and password rejection. */
object RecorderErrors {
    fun disconnected(reason: String): String =
        when (reason) {
            "speed_err" ->
                "Регистратор отключил доступ: нет сигнала GPS или возможно движение автомобиля."
            "session_timeout" -> "Регистратор завершил сессию: не получен служебный ответ."
            "sdcard_err" -> "Регистратор отключил доступ из-за ошибки SD-карты."
            "battery_down" -> "Регистратор отключился из-за низкого заряда аккумулятора."
            "acc_off" -> "Питание ACC автомобиля выключено."
            "unexpected app" -> "Регистратор завершил сессию приложения."
            "navi_priority" -> "Регистратор передал приоритет навигации автомобиля."
            "module_reset" -> "Модуль регистратора перезапускается."
            else -> "Соединение с регистратором прервано."
        }

    fun describe(code: Int): String =
        when (code) {
            0 -> "Успешно."
            -4 -> "Сессия регистратора недействительна (-4)."
            -21 -> "Регистратор занят другой командой; повторите позже (-21)."
            -29 -> "Регистратор отклонил пароль (-29)."
            -50 -> "Регистратор не принял название модели (-50)."
            -51 -> "Регистратор обрабатывает данные; подождите и повторите (-51)."
            -52 ->
                "Нет сигнала GPS или возможно движение автомобиля; доступ ограничен регистратором (-52)."
            -53 -> "Ошибка SD-карты регистратора (-53)."
            else -> "Регистратор отклонил запрос: rval=$code."
        }
}
